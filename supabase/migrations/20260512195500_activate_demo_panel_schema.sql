create extension if not exists pgcrypto;

create table if not exists public.facilities (
    id uuid primary key default gen_random_uuid(),
    code text not null unique,
    name text not null,
    testing_plan text not null default 'starter',
    created_at timestamptz not null default now()
);

create table if not exists public.staff_profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    facility_id uuid not null references public.facilities (id) on delete cascade,
    role text not null,
    display_name text not null,
    subscription_tier text not null default 'starter',
    beta_track text not null default 'care',
    is_demo boolean not null default false,
    created_at timestamptz not null default now(),
    constraint staff_profiles_role_check check (role in ('creator', 'admin', 'administrator', 'tester', 'nurse', 'carer', 'caregiver')),
    constraint staff_profiles_subscription_check check (subscription_tier in ('starter', 'carePro', 'careTeam'))
);

create table if not exists public.residents (
    id uuid primary key default gen_random_uuid(),
    facility_id uuid not null references public.facilities (id) on delete cascade,
    name text not null,
    risk_level text,
    date_of_birth date,
    room_label text,
    created_at timestamptz not null default now(),
    constraint residents_risk_level_check check (risk_level is null or risk_level in ('low', 'medium', 'high'))
);

create table if not exists public.alerts (
    id bigint generated by default as identity primary key,
    facility_id uuid not null references public.facilities (id) on delete cascade,
    resident_id uuid not null references public.residents (id) on delete cascade,
    type text not null,
    status text not null default 'open',
    priority integer not null default 1,
    assigned_to uuid references public.staff_profiles (id) on delete set null,
    created_at timestamptz not null default now(),
    acknowledged_at timestamptz,
    closed_at timestamptz,
    close_notes text,
    constraint alerts_type_check check (type in ('fall', 'sos')),
    constraint alerts_status_check check (status in ('open', 'acknowledged', 'closed'))
);

create table if not exists public.vital_events (
    id bigint generated by default as identity primary key,
    facility_id uuid not null references public.facilities (id) on delete cascade,
    resident_id uuid not null references public.residents (id) on delete cascade,
    metric text not null,
    value double precision not null,
    observed_at timestamptz not null default now(),
    recorded_by uuid references public.staff_profiles (id) on delete set null
);

create table if not exists public.handoff_requests (
    id bigint generated by default as identity primary key,
    facility_id uuid not null references public.facilities (id) on delete cascade,
    resident_id uuid not null references public.residents (id) on delete cascade,
    notes text,
    request_token text not null default gen_random_uuid()::text unique,
    created_at timestamptz not null default now(),
    resolved_at timestamptz,
    resolved_by uuid references public.staff_profiles (id) on delete set null
);

create index if not exists idx_staff_profiles_facility_id on public.staff_profiles (facility_id);
create index if not exists idx_residents_facility_id on public.residents (facility_id);
create index if not exists idx_alerts_facility_status_created_at on public.alerts (facility_id, status, created_at desc);
create index if not exists idx_alerts_resident_type_created_at on public.alerts (resident_id, type, created_at desc);
create index if not exists idx_vital_events_resident_observed_at on public.vital_events (resident_id, observed_at desc);
create index if not exists idx_handoff_requests_facility_created_at on public.handoff_requests (facility_id, created_at desc)
    where resolved_at is null;

create or replace function public.current_staff_facility_id()
returns uuid
language sql
stable
as $$
    select facility_id
    from public.staff_profiles
    where id = auth.uid()
$$;

