create or replace function public.get_facility_stats(p_facility_id uuid)
returns table (
    falls_last_7d integer,
    open_alerts integer,
    avg_acknowledge_minutes integer
)
language sql
security definer
set search_path = public
as $$
    select
        count(*) filter (
            where a.type = 'fall'
              and a.created_at >= now() - interval '7 days'
        )::integer as falls_last_7d,
        count(*) filter (where a.status <> 'closed')::integer as open_alerts,
        coalesce(
            avg(
                case
                    when a.acknowledged_at is not null then extract(epoch from (a.acknowledged_at - a.created_at)) / 60.0
                end
            )::integer,
            0
        ) as avg_acknowledge_minutes
    from public.alerts a
    where a.facility_id = p_facility_id
$$;

