create or replace function public.get_open_alerts_for_facility(p_facility_id uuid)
returns table (
    id bigint,
    resident_id uuid,
    type text,
    status text,
    priority integer,
    created_at timestamptz,
    assigned_to uuid
)
language sql
security definer
set search_path = public
as $$
    select a.id, a.resident_id, a.type, a.status, a.priority, a.created_at, a.assigned_to
    from public.alerts a
    where a.facility_id = p_facility_id
      and a.status <> 'closed'
    order by a.created_at desc
$$;

create or replace function public.acknowledge_alert(
    p_alert_id bigint,
    p_staff_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.alerts
    set status = 'acknowledged',
        assigned_to = p_staff_id,
        acknowledged_at = coalesce(acknowledged_at, now())
    where id = p_alert_id;
end;
$$;

