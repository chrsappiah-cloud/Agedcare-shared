create or replace function public.get_staff_info(p_user_id uuid)
returns table (
    id text,
    facility_id text,
    role text,
    display_name text
)
language sql
security definer
set search_path = public
as $$
    select sp.id::text, sp.facility_id::text, sp.role, sp.display_name
    from public.staff_profiles sp
    where sp.id = p_user_id
$$;

create or replace function public.create_fall_alert(
    p_facility_id uuid,
    p_resident_id uuid,
    p_priority integer default 2
)
returns table (alert_id bigint)
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.alerts (facility_id, resident_id, type, status, priority)
    values (p_facility_id, p_resident_id, 'fall', 'open', greatest(coalesce(p_priority, 2), 1))
    returning id into alert_id;

    return next;
end;
$$;

