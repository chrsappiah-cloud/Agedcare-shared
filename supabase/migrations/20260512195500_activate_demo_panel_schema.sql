create or replace function public.resolve_handoff_request(p_alert_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.handoff_requests
    set resolved_at = now(),
        resolved_by = auth.uid()
    where request_token = p_alert_id
       or id::text = p_alert_id;
end;
$$;

create or replace function public.get_pending_handoffs(p_facility_id uuid)
returns table (
    id integer,
    "facilityId" text,
    "residentId" text,
    "createdAt" text,
    notes text
)
language sql
security definer
set search_path = public
as $$
    select
        hr.id::integer,
        hr.facility_id::text as "facilityId",
        hr.resident_id::text as "residentId",
        to_char(hr.created_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') as "createdAt",
        hr.notes
    from public.handoff_requests hr
    where hr.facility_id = p_facility_id
      and hr.resolved_at is null
    order by hr.created_at desc
$$;

create or replace function public.get_residents_for_facility(p_facility_id uuid)
returns table (
    id uuid,
    facility_id uuid,
    name text,
    risk_level text,
    date_of_birth text
)
language sql
security definer
set search_path = public
as $$
    select
        r.id,
        r.facility_id,
        r.name,
        r.risk_level,
        case
            when r.date_of_birth is null then null
            else to_char(r.date_of_birth, 'YYYY-MM-DD') || 'T00:00:00Z'
        end as date_of_birth
    from public.residents r
    where r.facility_id = p_facility_id
    order by r.name
$$;

create or replace function public.get_fall_summary_for_resident(
    p_resident_id uuid,
    p_days integer default 7
)
returns integer
language sql
security definer
set search_path = public
as $$
    select count(*)::integer
    from public.alerts a
    where a.resident_id = p_resident_id
      and a.type = 'fall'
      and a.created_at >= now() - make_interval(days => greatest(coalesce(p_days, 7), 1))
$$;

create or replace function public.get_resident_timeline(
    p_resident_id uuid,
    p_limit integer default 50
)
returns table (
    kind text,
    ts text,
    summary text
)
language sql
security definer
set search_path = public
as $$
    with timeline as (
        select
            a.created_at as event_time,
            a.type as kind,
            initcap(a.type) || ' alert (' || a.status || ')' as summary
        from public.alerts a
        where a.resident_id = p_resident_id
        union all
        select
            v.observed_at as event_time,
            'vital' as kind,
            initcap(replace(v.metric, '_', ' ')) || ': ' || trim(to_char(v.value, 'FM999999990.00')) as summary
        from public.vital_events v
        where v.resident_id = p_resident_id
    )
    select
        timeline.kind,
        to_char(timeline.event_time at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') as ts,
        timeline.summary
    from timeline
    order by timeline.event_time desc
    limit greatest(coalesce(p_limit, 50), 1)
$$;

